function mapControlledOption(value: string): string {
  return (
    surgeryNewDisplayLabels.es[value]
    ?? surgeryNewExamLabels.es[value]
    ?? surgeryNewArthroplastyDisplayLabels.es[value]
    ?? surgeryNewTraumaDisplayLabels.es[value]
    ?? controlledEs[value]
    ?? value
  );
}

export function surgeryPdfAuthoredText(locale: Locale, value: string): string {
  if (locale !== "es") return value;
  const numbered = value.match(/^(\d+\.\s*)(.+)$/);
  if (numbered) return `${numbered[1]}${authoredEs[numbered[2]] ?? numbered[2]}`;
  return authoredEs[value] ?? value;
}

/**
 * Localizes persisted/generated controlled values. Unknown values are returned
 * byte-for-byte so custom entries and clinical free text are never guessed.
 */
export function surgeryPdfControlledText(locale: Locale, value: string): string {
  if (locale !== "es" || !value) return value;

  const option = mapControlledOption(value);
  if (option !== value) return option;

  const technique = displaySurgeryTechniqueOption(locale, value);
  if (technique !== value) return technique;

  return value;
}

/** Only for deterministic BioReady/renderer output, never clinician text. */
export function surgeryPdfGeneratedClinicalText(locale: Locale, value: string): string {
  if (locale !== "es" || !value) return value;
  const exact = surgeryPdfControlledText(locale, value);
  if (exact !== value) return exact;
  return controlledPhraseEs.reduce(
    (translated, [source, target]) => translated.replaceAll(source, target),
    value,
  );
}

